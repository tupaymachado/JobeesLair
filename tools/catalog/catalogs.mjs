#!/usr/bin/env node
// Builds app/data/catalogs.js: which catalogs list each bundled game (app/state/catalogs.js), so the store can
// filter by catalog without reading 2,000 release files on the console. The catalog feeds add their own games
// when they load (app/state/catalog.js).
//
//   node tools/catalog/catalogs.mjs
//
// Run it again whenever the bundled releases change; tests/catalogs.test.mjs checks the file is current.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const { catalogsOf } = await import(pathToFileURL(path.join(repo, 'app/state/catalogs.js')).href);
const { readJlx } = await import(pathToFileURL(path.join(repo, 'app/state/jlx.js')).href);

export function buildCatalogs(dir = path.join(repo, 'app/data/releases')) {
  const out = {};
  for (const name of fs.readdirSync(dir).filter((file) => file.endsWith('.json')).sort()) {
    const ids = new Set(JSON.parse(readJlx(fs.readFileSync(path.join(dir, name), 'utf8'))).flatMap(catalogsOf));
    if (ids.size) out[name.slice(0, -5)] = [...ids].sort().join(' ');
  }
  return out;
}

export function catalogsModule(catalogs) {
  const lines = Object.entries(catalogs).map(([id, list]) => `    ${JSON.stringify(id)}: ${JSON.stringify(list)}`);
  return [
    '// Generated by tools/catalog/catalogs.mjs from app/data/releases: the catalogs that list each bundled game,',
    '// space-separated (app/state/catalogs.js). Do not edit; run the tool again.',
    '',
    '  var catalogs = {',
    lines.join(',\n'),
    '  };',
    '',
    'export { catalogs };',
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const catalogs = buildCatalogs();
  fs.writeFileSync(path.join(repo, 'app/data/catalogs.js'), catalogsModule(catalogs));
  console.log(`app/data/catalogs.js: ${Object.keys(catalogs).length} games`);
}
